#!/usr/bin/env node
// Regenerates Sources/ZerohashSDK/Internal/WalletSchemes.generated.swift from
// Dynamic's wallet book: the custom URL scheme of every wallet's mobile deep link.
//
//   node scripts/generate-wallet-schemes.mjs              fetch the wallet book
//   node scripts/generate-wallet-schemes.mjs --from f.json  use a local copy
//
// Keep the extraction rules identical to WalletBookParser in WalletSchemeStore.swift.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const WALLET_BOOK_URL = 'https://dynamic-static-assets.com/wallet-book/v1/stable/wallet-book.json';
const OUTPUT = join(dirname(fileURLToPath(import.meta.url)), '../Sources/ZerohashSDK/Internal/WalletSchemes.generated.swift');
const SCHEME = /^[a-z][a-z0-9+.-]*$/;
const RESERVED = new Set([
  'http', 'https', 'ws', 'wss', 'ftp', 'file', 'data', 'blob', 'about', 'javascript',
  'tel', 'sms', 'mailto', 'facetime', 'facetime-audio',
  'itms', 'itms-apps', 'itms-services', 'app-prefs', 'prefs', 'shortcuts',
  'content', 'intent',
]);

const fromIndex = process.argv.indexOf('--from');
const source = fromIndex > -1 ? readFileSync(process.argv[fromIndex + 1], 'utf8') : await (await fetch(WALLET_BOOK_URL)).text();
const book = JSON.parse(source);

const schemes = new Set();
for (const wallet of Object.values(book.wallets ?? {})) {
  const native = wallet?.mobile?.native;
  if (typeof native !== 'string') continue;
  const scheme = native.trim().split(':', 1)[0].toLowerCase();
  if (SCHEME.test(scheme) && !RESERVED.has(scheme)) schemes.add(scheme);
}

const sorted = [...schemes].sort();
const body = sorted.map((s) => `        "${s}",`).join('\n');
writeFileSync(
  OUTPUT,
  `// @generated by scripts/generate-wallet-schemes.mjs from ${WALLET_BOOK_URL}
// Do not edit by hand; rerun the script.
enum WalletSchemeSnapshot {
    static let schemes: Set<String> = [
${body}
    ]
}
`
);
console.log(`${sorted.length} schemes -> ${OUTPUT}`);
